ACTIVE_UNIT_VARIANCE_THRESHOLD = 0.01
SPARSITY_NEAR_ZERO_THRESHOLD = 0.01


def extract_all_z_values(vae_model, dataloader):
    vae_model.eval()
    all_z = []
    with torch.no_grad():
        for batch in dataloader:
            batch = batch.to(DEVICE)
            alpha = vae_model.encode(batch)
            z = vae_model.reparameterize(alpha)
            all_z.append(z.cpu().numpy())
    return np.vstack(all_z)


def calculate_vae_metrics(all_z_values, vae_model, dataloader, recon_percentile=25):
    metrics = {}
    recon_errors = []
    vae_model.eval()
    with torch.no_grad():
        for batch in dataloader:
            batch = batch.to(DEVICE)
            recon_batch, _, _ = vae_model(batch)
            errors = torch.mean((recon_batch - batch) ** 2, dim=1)
            recon_errors.extend(errors.cpu().numpy())

    recon_errors = np.array(recon_errors)
    metrics['reconstruction_error_mean'] = float(np.mean(recon_errors))
    metrics['reconstruction_error_std'] = float(np.std(recon_errors))

    threshold = np.percentile(recon_errors, recon_percentile)
    metrics['reconstruction_accuracy'] = float(np.mean(recon_errors < threshold))
    metrics['recon_threshold_used'] = float(threshold)

    z_var = np.var(all_z_values, axis=0)
    active_units = int(np.sum(z_var > ACTIVE_UNIT_VARIANCE_THRESHOLD))
    metrics['active_units'] = active_units
    metrics['active_units_ratio'] = active_units / all_z_values.shape[1]
    metrics['active_units_variance_threshold'] = ACTIVE_UNIT_VARIANCE_THRESHOLD

    if len(all_z_values) > 10 and all_z_values.shape[1] > 1:
        try:
            n_clusters = min(10, all_z_values.shape[0] // 10 + 1)
            kmeans = KMeans(n_clusters=n_clusters, random_state=42, n_init=10)
            labels = kmeans.fit_predict(all_z_values)
            metrics['silhouette_score'] = float(silhouette_score(all_z_values, labels))
        except Exception:
            metrics['silhouette_score'] = 0.0
    else:
        metrics['silhouette_score'] = 0.0

    metrics['sparsity'] = float(np.mean(all_z_values < SPARSITY_NEAR_ZERO_THRESHOLD))
    metrics['sparsity_near_zero_threshold'] = SPARSITY_NEAR_ZERO_THRESHOLD

    return metrics


