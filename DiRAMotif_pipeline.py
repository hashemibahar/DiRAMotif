def get_top_kmers_per_z(all_z_values, kmer_features, kmer_dict, sequences, k, top_n=30):
    num_z_dims = all_z_values.shape[1]
    top_kmers = {}
    idx_to_kmer = {v: kk for kk, v in kmer_dict.items()}

    for z_dim in range(num_z_dims):
        z_scores = all_z_values[:, z_dim]
        top_indices = np.argsort(z_scores)[-top_n:]
        kmer_counter = Counter()
        for idx in top_indices:
            kmer_counts_row = kmer_features[idx]
            for kmer_idx in np.where(kmer_counts_row > 0)[0]:
                kmer = idx_to_kmer[kmer_idx]
                if len(kmer) == k:
                    kmer_counter[kmer] += int(kmer_counts_row[kmer_idx])
        top_kmers[z_dim] = {
            'kmers': [(kmer, count) for kmer, count in kmer_counter.most_common(top_n)],
            'sequences': [sequences[idx] for idx in top_indices]
        }
    return top_kmers


def plot_motif_activity_heatmap(top_kmers, top_motifs_list, save_path, protein_name):
    num_z_dims = len(top_kmers)
    num_motifs = len(top_motifs_list)
    activity_matrix = np.zeros((num_z_dims, num_motifs))

    for z_dim in range(num_z_dims):
        kmers_in_z = {kmer: count for kmer, count in top_kmers[z_dim]['kmers']}
        for j, motif in enumerate(top_motifs_list):
            activity_matrix[z_dim, j] = kmers_in_z.get(motif, 0)

    row_max = activity_matrix.max(axis=1, keepdims=True)
    row_max[row_max == 0] = 1
    activity_matrix_norm = activity_matrix / row_max

    plt.figure(figsize=(18, 12))
    sns.heatmap(
        activity_matrix_norm, cmap='YlOrRd', cbar_kws={'label': 'Normalized K-mer Activity'},
        xticklabels=top_motifs_list, yticklabels=[f'Z{i}' for i in range(num_z_dims)],
        linewidths=0.5, linecolor='gray'
    )
    plt.title(f'{protein_name} — Motif Activity Patterns Across Latent Dimensions', fontweight='bold', pad=20)
    plt.xlabel('Top RBP-Specific Motifs'); plt.ylabel('Latent Dimensions (Z)')
    plt.xticks(rotation=45, ha='right', fontsize=9)
    plt.tight_layout()
    plt.savefig(os.path.join(save_path, f'{protein_name}_motif_activity_heatmap.jpg'), dpi=300, bbox_inches='tight')
    plt.close()


