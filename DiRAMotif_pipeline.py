def count_kmers_rna(sequence, k=6):
    sequence = sequence.replace('T', 'U').replace('t', 'u').upper()
    valid_chars = set('ACGU')
    sequence = ''.join([c for c in sequence if c in valid_chars])
    kmer_counts = Counter()
    for i in range(len(sequence) - k + 1):
        kmer = sequence[i:i + k]
        if 'N' not in kmer and len(kmer) == k:
            kmer_counts[kmer] += 1
    return kmer_counts


def load_fasta_records(fasta_file):
    records = []
    for record in SeqIO.parse(fasta_file, "fasta"):
        records.append((record.id, str(record.seq)))
    return records


