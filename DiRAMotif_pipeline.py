def dinucleotide_shuffle(seq, num_shuffles=10):
    if len(seq) < 2:
        return seq
    seq = seq.upper().replace('T', 'U')
    seq = ''.join([c for c in seq if c in 'ACGU'])
    if len(seq) < 2:
        return ''.join(random.choices('ACGU', k=len(seq)))

    di_nuc_counts = Counter()
    for i in range(len(seq) - 1):
        di_nuc_counts[seq[i:i + 2]] += 1

    graph = defaultdict(list)
    for dn, count in di_nuc_counts.items():
        for _ in range(count):
            graph[dn[0]].append(dn[1])

    start_char = seq[0]
    result = [start_char]
    current = start_char
    edges_used = 0
    total_edges = sum(len(v) for v in graph.values())

    while edges_used < total_edges and current in graph and graph[current]:
        next_char = graph[current].pop()
        result.append(next_char)
        current = next_char
        edges_used += 1

    if len(result) < len(seq):
        result = list(seq)
        random.shuffle(result)

    return ''.join(result[:len(seq)])


def generate_dinucleotide_shuffled_background(sequences, num_shuffles=5):
    background = []
    for seq in sequences:
        seq_str = str(seq).upper().replace('T', 'U')
        seq_str = ''.join([c for c in seq_str if c in 'ACGU'])
        if len(seq_str) < 6:
            continue
        for _ in range(num_shuffles):
            shuffled = dinucleotide_shuffle(seq_str, num_shuffles=20)
            background.append(shuffled)
    return background


def calculate_enrichment_pvalue_and_qvalue(candidate_kmers, peak_seqs, background_seqs):
    pvals, kmers_list = [], []
    for kmer in candidate_kmers:
        a = sum(1 for seq in peak_seqs if kmer in seq)
        b = len(peak_seqs) - a
        c = sum(1 for seq in background_seqs if kmer in seq)
        d = len(background_seqs) - c
        if a + b == 0 or c + d == 0 or a + c == 0 or b + d == 0:
            p_val = 1.0
        else:
            try:
                _, p_val = fisher_exact([[a, b], [c, d]], alternative='greater')
            except Exception:
                p_val = 1.0
        pvals.append(p_val)
        kmers_list.append(kmer)

    pvals = np.array(pvals)
    _, qvals = fdrcorrection(pvals, alpha=0.05, method='indep')
    if qvals is None:
        qvals = pvals.copy()

    return {kmer: {'pval': float(pvals[i]), 'qval': float(qvals[i])} for i, kmer in enumerate(kmers_list)}


def precompute_accessibility_profiles(sequences, seq_ids=None, real_icshape=None,
                                       max_null_fraction_allowed=MAX_ICSHAPE_NULL_FRACTION):
    if seq_ids is None:
        seq_ids = [None] * len(sequences)
    if real_icshape is None:
        real_icshape = {}

    profiles = []
    n_real, n_computed, n_failed = 0, 0, 0

    for seq, sid in zip(sequences, seq_ids):
        clean_seq = ''.join(c for c in seq.upper().replace('T', 'U') if c in 'ACGU')
        if not clean_seq:
            profiles.append(np.array([]))
            n_failed += 1
            continue

        used_real = False
        if sid is not None and sid in real_icshape:
            raw_scores = real_icshape[sid]
            if raw_scores is not None and len(raw_scores) == len(clean_seq):
                null_frac = sum(1 for v in raw_scores if v is None) / len(raw_scores)
                if null_frac <= max_null_fraction_allowed:
                    profile = np.array([np.nan if v is None else float(v) for v in raw_scores])
                    profiles.append(profile)
                    n_real += 1
                    used_real = True

        if not used_real:
            try:
                fc = RNA.fold_compound(clean_seq)
                fc.pf()
                n = len(clean_seq)
                bpp = fc.bpp()
                unpaired = np.ones(n, dtype=np.float64)
                for i in range(1, n + 1):
                    total_pair_prob = 0.0
                    for j in range(1, n + 1):
                        if i != j and bpp[i][j] > 0:
                            total_pair_prob += bpp[i][j]
                    unpaired[i - 1] = max(0.0, 1.0 - total_pair_prob)
                unpaired = np.clip(unpaired, 0.0, 1.0)
                profiles.append(unpaired)
                n_computed += 1
            except Exception as e:
                print(f"  Warning: ViennaRNA folding failed (len={len(clean_seq)}): {str(e)[:100]}")
                profiles.append(np.full(len(clean_seq), np.nan))
                n_failed += 1

    total = len(sequences)
    if n_real > 0 and n_computed == 0:
        source_label = "real_icshape_experimental"
    elif n_real > 0 and n_computed > 0:
        source_label = "mixed_real_icshape_and_computational_fold"
    else:
        source_label = "ViennaRNA_computational_fold"

    summary = {
        'n_real_icshape_used': n_real,
        'n_computational_fold_used': n_computed,
        'n_failed': n_failed,
        'total': total,
        'accessibility_source': source_label,
    }
    print(f"    Accessibility source: {n_real}/{total} real icSHAPE scores, "
          f"{n_computed}/{total} ViennaRNA computational folds, {n_failed} failed.")
    return profiles, summary


def calculate_accessibility_score_optimized(kmer, peak_seqs, accessibility_profiles):
    total_accessibility, count = 0.0, 0
    clean_kmer = kmer.upper().replace('T', 'U')
    clean_kmer = ''.join([c for c in clean_kmer if c in 'ACGU'])
    if len(clean_kmer) != len(kmer):
        return 0.0

    for orig_seq, profile in zip(peak_seqs, accessibility_profiles):
        if len(profile) == 0:
            continue
        clean_seq = orig_seq.upper().replace('T', 'U')
        clean_seq = ''.join([c for c in clean_seq if c in 'ACGU'])

        if clean_kmer not in clean_seq:
            continue

        start = 0
        while True:
            pos = clean_seq.find(clean_kmer, start)
            if pos == -1:
                break
            kmer_end = pos + len(clean_kmer)
            if kmer_end <= len(profile):
                window_vals = profile[pos:kmer_end]
            else:
                window_vals = profile[pos:]
            if len(window_vals) > 0:
                valid_vals = window_vals[~np.isnan(window_vals)]
                if len(valid_vals) > 0:
                    total_accessibility += float(np.mean(valid_vals))
                    count += 1
            start = pos + 1

    return total_accessibility / count if count > 0 else 0.0


def calculate_centrality_score(kmer, peak_seqs):
    total_norm_dist, count = 0.0, 0
    for seq in peak_seqs:
        if kmer not in seq:
            continue
        peak_center = len(seq) / 2.0
        start = 0
        while True:
            pos = seq.find(kmer, start)
            if pos == -1:
                break
            kmer_center = pos + len(kmer) / 2.0
            distance = abs(kmer_center - peak_center)
            normalized_dist = 1.0 - (distance / (len(seq) / 2.0 + 1e-8))
            total_norm_dist += max(0.0, min(1.0, normalized_dist))
            count += 1
            start = pos + 1
    return total_norm_dist / count if count > 0 else 0.0


def normalize_enrichment_score(p_val):
    log_score = -np.log10(p_val + 1e-10)
    return 1 / (1 + np.exp(-(log_score - 2)))


def rbp_specific_postprocessing(candidate_kmers, peak_seqs, peak_ids=None,
                                 real_icshape=None, real_negative_seqs=None,
                                 min_real_negatives=MIN_REAL_NEGATIVES_FOR_BACKGROUND):
    if real_negative_seqs is not None and len(real_negative_seqs) >= min_real_negatives:
        background_seqs = real_negative_seqs
        background_source = "real_non_enriched_clip_background (experimentally derived negative set)"
        print(f"    Background: using {len(background_seqs)} real negative sequences.")
    else:
        background_seqs = generate_dinucleotide_shuffled_background(peak_seqs, num_shuffles=5)
        if len(background_seqs) == 0:
            background_seqs = peak_seqs
        background_source = "dinucleotide_shuffle"
        n_avail = len(real_negative_seqs) if real_negative_seqs is not None else 0
        print(f"    Background: available real negatives ({n_avail}) insufficient "
              f"(minimum required={min_real_negatives}); using dinucleotide shuffle instead.")

    enrichment_results = calculate_enrichment_pvalue_and_qvalue(candidate_kmers, peak_seqs, background_seqs)
    accessibility_profiles, acc_summary = precompute_accessibility_profiles(
        peak_seqs, seq_ids=peak_ids, real_icshape=real_icshape
    )

    accessibility_scores, centrality_scores = {}, {}
    for kmer in candidate_kmers:
        accessibility_scores[kmer] = calculate_accessibility_score_optimized(
            kmer, peak_seqs, accessibility_profiles
        )
        centrality_scores[kmer] = calculate_centrality_score(kmer, peak_seqs)

    rbp_scores = {}
    for kmer in candidate_kmers:
        pval = enrichment_results[kmer]['pval']
        qval = enrichment_results[kmer]['qval']
        enrichment_norm = normalize_enrichment_score(pval)
        final_score = (0.5 * enrichment_norm) + (0.3 * accessibility_scores[kmer]) + (0.2 * centrality_scores[kmer])
        rbp_scores[kmer] = {
            'rbp_final_score': final_score,
            'enrichment_pval': pval,
            'enrichment_qval': qval,
            'enrichment_norm': enrichment_norm,
            'accessibility': accessibility_scores[kmer],
            'centrality': centrality_scores[kmer]
        }

    metadata = {
        'background_source': background_source,
        'n_background_sequences': len(background_seqs),
        'n_real_negatives_available': len(real_negative_seqs) if real_negative_seqs is not None else 0,
        'min_real_negatives_required': min_real_negatives,
        **acc_summary,
    }
    return rbp_scores, metadata


