class VAE_Dirichlet(nn.Module):
    def __init__(self, input_dim, hidden_dim, latent_dim, dropout_rate=DROPOUT_RATE):
        super(VAE_Dirichlet, self).__init__()
        self.input_dim = input_dim
        self.hidden_dim = hidden_dim
        self.latent_dim = latent_dim
        self.dropout_rate = dropout_rate

        self.encoder = nn.Sequential(
            nn.Linear(input_dim, hidden_dim),
            nn.ReLU(),
            nn.LayerNorm(hidden_dim),
            nn.Dropout(dropout_rate),
            nn.Linear(hidden_dim, latent_dim)
        )
        self.decoder = nn.Sequential(
            nn.Linear(latent_dim, hidden_dim),
            nn.ReLU(),
            nn.LayerNorm(hidden_dim),
            nn.Dropout(dropout_rate),
            nn.Linear(hidden_dim, input_dim),
            nn.Sigmoid()
        )

    def encode(self, x):
        alpha = self.encoder(x)
        alpha = torch.clamp(alpha, min=1e-6, max=1e6)
        alpha = torch.nn.functional.softmax(alpha, dim=-1)
        return alpha

    def reparameterize(self, alpha):
        alpha = torch.clamp(alpha, min=1e-6)
        gamma = torch.distributions.Gamma(alpha, torch.ones_like(alpha)).sample()
        z = gamma / (gamma.sum(-1, keepdim=True) + 1e-8)
        return z

    def decode(self, z):
        return self.decoder(z)

    def forward(self, x):
        alpha = self.encode(x)
        z = self.reparameterize(alpha)
        return self.decode(z), alpha, z


def dirichlet_loss_split(recon_x, x, alpha, prior_alpha=0.1):
    recon_loss = nn.functional.mse_loss(recon_x, x, reduction='sum')

    def kl_divergence_dirichlet(alpha, prior_alpha):
        prior_alpha_tensor = torch.tensor(prior_alpha, dtype=alpha.dtype, device=alpha.device)
        term1 = torch.lgamma(alpha.sum(-1)) - torch.lgamma(prior_alpha_tensor * alpha.shape[-1])
        term2 = torch.sum(torch.lgamma(prior_alpha_tensor) - torch.lgamma(alpha), dim=-1)
        term3 = torch.sum(
            (alpha - prior_alpha_tensor) * (torch.digamma(alpha) - torch.digamma(alpha.sum(-1, keepdim=True))),
            dim=-1
        )
        return term1 + term2 + term3

    kl_loss = kl_divergence_dirichlet(alpha, prior_alpha).sum()
    total_loss = recon_loss + kl_loss
    return total_loss, recon_loss, kl_loss


