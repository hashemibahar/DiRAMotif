def run_multi_k_robustness_analysis(train_sequences, test_sequences, save_path, protein_name,
                                      k_values=(4, 5, 6, 7), reference_k=6,
                                      hidden_dim=200, latent_dim=30, epochs=100, top_n=30):
    print(f"  --- Multi-k robustness analysis for {protein_name} (k={k_values}) ---")
    results_per_k = {}
    for k in k_values:
        print(f"    Training independent model with k={k} ...")
        Xtr, kdict = extract_rna_kmer_features_with_shared_dict(train_sequences, k=k)
        Xte, _ = extract_rna_kmer_features_with_shared_dict(test_sequences, k=k, kmer_dict=kdict)
        model, history, train_loader, _ = train_vae_with_real_holdout(
            Xtr, Xte, Xtr.shape[1], hidden_dim, latent_dim, epochs=epochs, verbose=False
        )
        all_z = extract_all_z_values(model, train_loader)
        top_kmers = get_top_kmers_per_z(all_z, Xtr, kdict, train_sequences, k=k, top_n=top_n)
        merged_kmers = set()
        for z_dim, data in top_kmers.items():
            for kmer, count in data['kmers']:
                merged_kmers.add(kmer)
        results_per_k[k] = merged_kmers
        print(f"      -> {len(merged_kmers)} unique candidate motifs for k={k}")

    reference_set = results_per_k[reference_k]
    rows = []
    for k in k_values:
        if k == reference_k:
            continue
        other_set = results_per_k[k]
        n_contained = 0
        for ref_motif in reference_set:
            match_found = False
            for other_motif in other_set:
                if (ref_motif in other_motif) or (other_motif in ref_motif):
                    match_found = True
                    break
            if match_found:
                n_contained += 1
        agreement_pct = 100.0 * n_contained / len(reference_set) if reference_set else 0.0
        rows.append({
            'protein': protein_name,
            'k_reference': reference_k,
            'k_compared': k,
            'n_reference_motifs': len(reference_set),
            'n_compared_motifs': len(other_set),
            'n_containment_matches': n_contained,
            'agreement_pct_vs_reference_k': round(agreement_pct, 2)
        })

    df = pd.DataFrame(rows)
    table5_path = os.path.join(save_path, f'{protein_name}_table5_multi_k_robustness.csv')
    df.to_csv(table5_path, index=False)
    print(f"  Table 5 (multi-k robustness) for {protein_name} saved to {table5_path}")
    return df, results_per_k


