def extract_rna_kmer_features_with_shared_dict(sequences, k, kmer_dict=None):
    build_dict = kmer_dict is None
    if build_dict:
        kmer_dict = {}

    all_kmer_counts = []
    for sequence in sequences:
        kmer_counts = count_kmers_rna(sequence, k=k)
        all_kmer_counts.append(kmer_counts)
        if build_dict:
            for kmer in kmer_counts:
                if kmer not in kmer_dict:
                    kmer_dict[kmer] = len(kmer_dict)

    feature_matrix = np.zeros((len(sequences), len(kmer_dict)), dtype=np.float32)
    for i, kmer_counts in enumerate(all_kmer_counts):
        for kmer, count in kmer_counts.items():
            if kmer in kmer_dict:
                feature_matrix[i, kmer_dict[kmer]] = count

    return feature_matrix, kmer_dict


